// Builds the Ads Bot weekly-digest WhatsApp template module from the Noa-gated final JSON in docs/copy.
// HEBREW-SAFETY: this script is ASCII-only and never contains Hebrew. Every line text is read, byte-exact, from
// `template_lines` of the source file and serialized with JSON.stringify.
//
// Only id / text / when are emitted. The render rules for each `when` live in src/lib/google-ads/whatsapp-digest.ts;
// this script fails closed if the source's ids, order or placeholders drift from what that renderer handles.
//
// To change the copy: change the docs/copy source (Tamar -> Noa), then run `node scripts/build-weekly-digest-copy.mjs`.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SOURCE = new URL('../docs/copy/ads-bot-weekly-digest-whatsapp-final-2026-11-12.json', import.meta.url);
export const OUTPUT = new URL('../src/lib/google-ads/weeklyDigestCopy.generated.ts', import.meta.url);
export const EXPORT_NAME = 'WEEKLY_DIGEST_TEMPLATE_LINES';

/** The ids the renderer handles, in source order, with the placeholders each line must carry. */
export const EXPECTED_LINES = [
  ['greeting', ['ownerName']],
  ['week_frame', ['campaignName']],
  ['leads_in', ['leadsIn']],
  ['marked_real', ['markedReal']],
  ['cost_per_real', ['costPerReal']],
  ['mark_nudge_zero', ['leadsLink']],
  ['unmarked_reminder', ['unmarked', 'leadsLink']],
  ['unmarked_reminder_one', ['leadsLink']],
  ['closed_deals_extra', ['closedDeals']],
  ['closed_deals_one', []],
  ['alerts_all_clear', []],
  ['support_close', []],
];

const PLACEHOLDER = /\{([A-Za-z]+)\}/g;

export function pick(src) {
  const lines = src?.template_lines;
  if (!Array.isArray(lines) || lines.length !== EXPECTED_LINES.length) {
    throw new Error(`Expected ${EXPECTED_LINES.length} template_lines, found ${Array.isArray(lines) ? lines.length : 'none'}`);
  }
  return lines.map((line, i) => {
    const [id, placeholders] = EXPECTED_LINES[i];
    if (line.id !== id) throw new Error(`template_lines[${i}]: expected id ${id}, found ${line.id}`);
    for (const k of ['text', 'when']) {
      if (typeof line[k] !== 'string' || !line[k] || line[k] !== line[k].trim()) throw new Error(`Empty, padded or non-string ${k}: ${id}`);
    }
    if (line.text.includes('  ')) throw new Error(`Double space: ${id}`);
    if (/["']/.test(line.text)) throw new Error(`ASCII quote in text: ${id}`);
    const found = [...line.text.matchAll(PLACEHOLDER)].map(m => m[1]);
    if (JSON.stringify(found) !== JSON.stringify(placeholders)) {
      throw new Error(`Placeholders for ${id}: expected ${placeholders.join(',') || 'none'}, found ${found.join(',') || 'none'}`);
    }
    if (line.text.replace(PLACEHOLDER, '').match(/[{}]/)) throw new Error(`Stray brace: ${id}`);
    return { id, text: line.text, when: line.when };
  });
}

export function generate(sourceText) {
  const lines = pick(JSON.parse(sourceText));
  // Empty ownerName drops " {ownerName}" (leading space included), so the greeting must carry it that way.
  if (!lines[0].text.includes(' {ownerName}')) throw new Error('greeting must contain " {ownerName}"');
  const rel = fileURLToPath(SOURCE).split('/docs/copy/')[1];
  return [
    '// GENERATED by scripts/build-weekly-digest-copy.mjs -- do not edit by hand.',
    `// Source (byte-exact, Noa-gated final template): docs/copy/${rel}`,
    '// Render rules for each `when`: src/lib/google-ads/whatsapp-digest.ts.',
    `export const ${EXPORT_NAME} = ${JSON.stringify(lines, null, 2)} as const;`,
    '',
  ].join('\n');
}

function main() {
  const next = generate(fs.readFileSync(SOURCE, 'utf8'));
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (current !== next) { console.error(`stale: ${fileURLToPath(OUTPUT)}`); process.exit(1); }
    return;
  }
  if (current !== next) { fs.writeFileSync(OUTPUT, next); console.log(`wrote ${fileURLToPath(OUTPUT)}`); }
  else console.log(`unchanged ${fileURLToPath(OUTPUT)}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
