// Builds src/lib/lp/heeboWidths.generated.json: the advance width (em) of each character the header logo estimates,
// measured in headless Chromium with the self-hosted Heebo the generated sites ship (siteFonts.ts), at weight 800 (the
// logo name's weight; the lighter descriptor / lockup rest are narrower, so the estimate stays on the safe side).
// Keys are decimal code points, so the output holds no Hebrew bytes. Re-run when siteFonts.ts changes:
//   node scripts/build-heebo-widths.mjs
// HEBREW-SAFETY: this file contains ZERO Hebrew bytes.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import puppeteer from 'puppeteer';
import { createTsRequire } from './lib/ts-require.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, 'src/lib/lp/heeboWidths.generated.json');
const WEIGHT = 800;
const { siteFontFiles, SITE_FONT_PATHS } = createTsRequire()('src/lib/lp/siteFonts.ts');
const files = siteFontFiles();
const hebrew = files[SITE_FONT_PATHS.hebrew.slice(1)];
const latin = files[SITE_FONT_PATHS.latin.slice(1)];

const codePoints = [];
for (let cp = 0x05d0; cp <= 0x05ea; cp++) codePoints.push(cp); // Hebrew letters
codePoints.push(0x05be, 0x05f3, 0x05f4); // maqaf, geresh, gershayim
for (let cp = 0x20; cp <= 0x7e; cp++) codePoints.push(cp); // printable ASCII
codePoints.push(0xb7, 0x2013, 0x2014, 0x2019, 0x201d, 0x20aa); // middle dot, dashes, quotes, shekel

const browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox'] });
const units = {};
try {
  const page = await browser.newPage();
  const face = (name, bytes) => `@font-face{font-family:${name};font-weight:400 800;src:url(data:font/woff2;base64,${bytes.toString('base64')}) format("woff2");}`;
  await page.setContent(`<style>${face('HeeboHe', hebrew)}${face('HeeboLa', latin)}</style><span id="s" style="font-family:HeeboHe,HeeboLa;font-size:100px;font-weight:${WEIGHT};white-space:pre;font-kerning:none"></span>`);
  await page.evaluate(async () => { await document.fonts.load('800 100px HeeboHe', '\u05d0'); await document.fonts.load('800 100px HeeboLa', 'a'); });
  for (const cp of codePoints) {
    // Ten copies: the average advance, rounded up to 1/1000 em.
    const width = await page.evaluate(code => {
      const span = document.getElementById('s');
      span.textContent = String.fromCodePoint(code).repeat(10);
      return span.getBoundingClientRect().width / 1000;
    }, cp);
    units[cp] = Math.ceil(width * 1000) / 1000;
  }
} finally {
  await browser.close();
}
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const out = {
  note: 'Generated by scripts/build-heebo-widths.mjs: Heebo advance widths in em at weight 800, keyed by decimal code point.',
  weight: WEIGHT,
  fonts: { hebrew: sha(hebrew), latin: sha(latin) },
  units,
};
fs.writeFileSync(OUT, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${path.relative(ROOT, OUT)} (${Object.keys(units).length} characters)`);
