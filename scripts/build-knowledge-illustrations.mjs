// Builds the knowledge-article illustration pilot (Yonatan's spec docs/specs/knowledge-illustrations-pilot-yonatan-2026-11-15.md).
// HEBREW-SAFETY: this script is ASCII-only and never contains Hebrew. Alt texts are read, byte-exact, from the approved
// waocopy file and serialized with JSON.stringify into src/data/knowledgeIllustrations.ts.
//
// Usage:
//   node scripts/build-knowledge-illustrations.mjs --data                 # regenerate the typed alt map only
//   node scripts/build-knowledge-illustrations.mjs --images <mastersDir>  # re-encode the masters (<slug>.png)
//   (both flags may be combined; the masters themselves are not committed)
//
// Outputs per slug in public/images/knowledge/ (centre crop, never upscaled past the master):
//   <slug>-800.avif|webp, <slug>-1200.avif|webp (16:9), <slug>-4x3.webp (1200x900), <slug>-1x1.webp (900x900),
//   <slug>-og.jpg (1200x630). Every file carries an XMP packet with IPTC DigitalSourceType = trainedAlgorithmicMedia.
// Idempotent: re-running overwrites the outputs. Fails closed if any file exceeds the byte budget or loses the XMP tag.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = fileURLToPath(new URL('..', import.meta.url));

export const SLUGS = [
  'local-seo', 'google-my-business', 'local-pack', 'google-ads-quality-score', 'search-intent', 'ai-overviews',
  'geo-audit-ai-overviews', 'international-seo', 'core-web-vitals', 'google-search-console', 'seo-audit', 'eeat',
];

export const ALTS_SOURCE = path.join(root, 'docs/copy/knowledge-illustration-alts-2026-11-15.waocopy.json');
export const DATA_OUTPUT = path.join(root, 'src/data/knowledgeIllustrations.ts');
export const OUT_DIR = path.join(root, 'public/images/knowledge');

export const DIGITAL_SOURCE_TYPE = 'http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia';
export const XMP = [
  '<?xpacket begin="\uFEFF" id="W5M0MpCehiHzreSzNTczkc9d"?>',
  '<x:xmpmeta xmlns:x="adobe:ns:meta/">',
  '<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">',
  '<rdf:Description rdf:about="" xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/">',
  `<Iptc4xmpExt:DigitalSourceType>${DIGITAL_SOURCE_TYPE}</Iptc4xmpExt:DigitalSourceType>`,
  '</rdf:Description>',
  '</rdf:RDF>',
  '</x:xmpmeta>',
  '<?xpacket end="w"?>',
].join('');

const BUDGET = 100_000; // bytes, strict decimal KB

// name suffix, width, height, format, starting quality
export const VARIANTS = [
  { suffix: '800', ext: 'avif', width: 800, height: 450, quality: 55 },
  { suffix: '800', ext: 'webp', width: 800, height: 450, quality: 78 },
  { suffix: '1200', ext: 'avif', width: 1200, height: 675, quality: 55 },
  { suffix: '1200', ext: 'webp', width: 1200, height: 675, quality: 78 },
  { suffix: '4x3', ext: 'webp', width: 1200, height: 900, quality: 78 },
  { suffix: '1x1', ext: 'webp', width: 900, height: 900, quality: 78 },
  { suffix: 'og', ext: 'jpg', width: 1200, height: 630, quality: 80 },
];

/** The JSON object starts at the first `{"alts"` (waocopy may prefix log text). */
export function readAlts(file = ALTS_SOURCE) {
  const text = fs.readFileSync(file, 'utf8');
  const at = text.indexOf('{"alts"');
  if (at < 0) throw new Error('No {"alts" object in alts source');
  let depth = 0;
  let inString = false;
  let end = -1;
  for (let i = at; i < text.length; i++) {
    const c = text[i];
    if (inString) {
      if (c === '\\') i++;
      else if (c === '"') inString = false;
    } else if (c === '"') inString = true;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) { end = i + 1; break; }
  }
  if (end < 0) throw new Error('Unterminated alts object');
  const { alts } = JSON.parse(text.slice(at, end));
  const keys = Object.keys(alts);
  if (keys.length !== SLUGS.length || !SLUGS.every(s => typeof alts[s] === 'string' && alts[s].length > 0)) {
    throw new Error(`Alt keys mismatch: ${keys.join(',')}`);
  }
  return alts;
}

export function renderDataModule(alts) {
  const lines = [
    '// GENERATED by scripts/build-knowledge-illustrations.mjs from',
    '// docs/copy/knowledge-illustration-alts-2026-11-15.waocopy.json. Do not edit by hand; edit the source and re-run.',
    '// Pilot of 12 knowledge-article illustrations (docs/specs/knowledge-illustrations-pilot-yonatan-2026-11-15.md).',
    '',
    'export type KnowledgeIllustration = { alt: string; width: 1600; height: 900 };',
    '',
    'export const KNOWLEDGE_ILLUSTRATIONS: Readonly<Record<string, KnowledgeIllustration>> = {',
    ...SLUGS.map(s => `  ${JSON.stringify(s)}: { alt: ${JSON.stringify(alts[s])}, width: 1600, height: 900 },`),
    '};',
    '',
    'const BASE = "https://www.wao.co.il/images/knowledge";',
    '',
    '/** Public paths of the pre-built files for one slug (served as-is, never re-encoded by next/image). */',
    'export function illustrationPaths(slug: string) {',
    '  const p = `/images/knowledge/${slug}`;',
    '  return {',
    '    avif800: `${p}-800.avif`,',
    '    avif1200: `${p}-1200.avif`,',
    '    webp800: `${p}-800.webp`,',
    '    webp1200: `${p}-1200.webp`,',
    '    og: `${p}-og.jpg`,',
    '  };',
    '}',
    '',
    '/** Article JSON-LD `image`: 16:9 (1200), 4:3 and 1:1 absolute URLs, or undefined for non-pilot slugs. */',
    'export function illustrationSchemaImages(slug: string): string[] | undefined {',
    '  if (!KNOWLEDGE_ILLUSTRATIONS[slug]) return undefined;',
    '  return [`${BASE}/${slug}-1200.webp`, `${BASE}/${slug}-4x3.webp`, `${BASE}/${slug}-1x1.webp`];',
    '}',
    '',
    '/** openGraph.images for pilot slugs (1200x630 JPEG), or undefined so other pages stay unchanged. */',
    'export function illustrationOgImages(slug: string) {',
    '  const ill = KNOWLEDGE_ILLUSTRATIONS[slug];',
    '  if (!ill) return undefined;',
    '  return [{ url: `${BASE}/${slug}-og.jpg`, width: 1200, height: 630, type: "image/jpeg", alt: ill.alt }];',
    '}',
    '',
  ];
  return lines.join('\n');
}

async function encode(input, v, quality) {
  let img = sharp(input).resize(v.width, v.height, { fit: 'cover', position: 'centre' }).withXmp(XMP);
  if (v.ext === 'avif') img = img.avif({ quality, effort: 6 });
  else if (v.ext === 'webp') img = img.webp({ quality, effort: 6 });
  else img = img.jpeg({ quality, mozjpeg: true, progressive: true });
  return img.toBuffer();
}

export async function buildImages(mastersDir) {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const report = [];
  for (const slug of SLUGS) {
    const input = fs.readFileSync(path.join(mastersDir, `${slug}.png`));
    for (const v of VARIANTS) {
      let quality = v.quality;
      let buf = await encode(input, v, quality);
      while (buf.length > BUDGET && quality > 30) {
        quality -= 5;
        buf = await encode(input, v, quality);
      }
      if (buf.length > BUDGET) throw new Error(`${slug}-${v.suffix}.${v.ext} over budget: ${buf.length}`);
      if (!buf.includes(Buffer.from(DIGITAL_SOURCE_TYPE))) throw new Error(`${slug}-${v.suffix}.${v.ext} lost XMP`);
      const meta = await sharp(buf).metadata();
      if (meta.width !== v.width || meta.height !== v.height) throw new Error(`${slug}-${v.suffix}.${v.ext} wrong size`);
      const name = `${slug}-${v.suffix}.${v.ext}`;
      fs.writeFileSync(path.join(OUT_DIR, name), buf);
      report.push({ name, bytes: buf.length, quality, xmp: Boolean(meta.xmp) });
    }
  }
  return report;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const args = process.argv.slice(2);
  if (args.includes('--data')) {
    fs.writeFileSync(DATA_OUTPUT, renderDataModule(readAlts()));
    console.log(`wrote ${path.relative(root, DATA_OUTPUT)}`);
  }
  const at = args.indexOf('--images');
  if (at >= 0) {
    const report = await buildImages(path.resolve(args[at + 1]));
    for (const r of report) console.log(`${r.name}\t${r.bytes}\tq${r.quality}\txmp=${r.xmp}`);
  }
  if (!args.includes('--data') && at < 0) console.error('usage: --data and/or --images <mastersDir>');
}
