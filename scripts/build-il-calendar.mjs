#!/usr/bin/env node
// Generates src/lib/calendar/il-blackout-dates.generated.ts from Hebcal's Israel holiday feed
// (post-launch week 1 spec, task A2). Dates are never typed by hand: re-run this script to
// extend the range.
//
//   node scripts/build-il-calendar.mjs [--start 2026-11-01] [--end 2027-12-31]
//
// Selection (deterministic, English titles only; no Hebrew is written):
//   - Tishrei run: every day from "Erev Rosh Hashana" through "Shmini Atzeret" (Israel), inclusive.
//   - Pesach run: every day from "Erev Pesach" through "Pesach VII", inclusive.
//   - Every other yom tov day (Hebcal `yomtov: true`, i.e. Shavuot) and its "Erev …" day.
//   - Yom HaZikaron + Yom HaAtzma'ut (statutory rest day and its eve).
// Chanukah, Purim, Tish'a B'Av and the minor/modern observances are working days and are not listed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'lib', 'calendar', 'il-blackout-dates.generated.ts');

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : fallback;
}

const start = arg('--start', '2026-11-01');
const end = arg('--end', '2027-12-31');
if (!/^\d{4}-\d{2}-\d{2}$/.test(start) || !/^\d{4}-\d{2}-\d{2}$/.test(end)) throw new Error('bad --start/--end');

export const SOURCE_URL = `https://www.hebcal.com/hebcal?v=1&cfg=json&maj=on&min=off&mod=on&nx=off&mf=off&ss=off&c=off&s=off&i=on&geo=none&start=${start}&end=${end}`;

const addDays = (iso, n) => new Date(Date.parse(`${iso}T00:00:00Z`) + n * 86_400_000).toISOString().slice(0, 10);

export function selectBlackoutDates(items) {
  const byDate = new Map();
  const add = (date, reason) => { if (!byDate.has(date)) byDate.set(date, reason); };
  const find = (title) => items.filter((i) => i.title === title).map((i) => i.date);
  const runs = [
    { name: 'Tishrei run', from: 'Erev Rosh Hashana', to: 'Shmini Atzeret' },
    { name: 'Pesach run', from: 'Erev Pesach', to: 'Pesach VII' },
  ];
  for (const run of runs) {
    const froms = find(run.from);
    const tos = find(run.to);
    for (const from of froms) {
      const to = tos.find((d) => d >= from && d <= addDays(from, 30));
      if (!to) throw new Error(`${run.name}: no "${run.to}" within 30 days of ${from}`);
      for (let d = from; d <= to; d = addDays(d, 1)) {
        const named = items.find((i) => i.date === d);
        add(d, `${run.name}: ${named ? named.title : 'between holidays'}`);
      }
    }
  }
  for (const item of items) {
    if (item.yomtov === true) add(item.date, item.title);
    if (/^Erev /.test(item.title) && items.some((i) => i.date === addDays(item.date, 1) && i.yomtov === true)) add(item.date, item.title);
    if (item.title === 'Yom HaZikaron' || /^Yom HaAtzma/.test(item.title)) add(item.date, item.title);
  }
  return [...byDate.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([date, reason]) => ({ date, reason }));
}

async function main() {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`Hebcal HTTP ${res.status}`);
  const body = await res.json();
  if (!Array.isArray(body.items) || !/Israel/.test(String(body.title))) throw new Error('unexpected Hebcal response (not the Israel calendar?)');
  const fetchedAt = new Date().toISOString();
  const dates = selectBlackoutDates(body.items);
  const ascii = (s) => s.replace(/[‘’]/g, "'").replace(/[^\x20-\x7e]/g, '');
  const lines = [
    '// GENERATED by scripts/build-il-calendar.mjs. Do not edit by hand; re-run the script.',
    `// Source: Hebcal Jewish calendar REST API, Israel schedule (i=on): ${SOURCE_URL}`,
    `// Fetched: ${fetchedAt} (Hebcal response date ${body.date ?? 'n/a'}; title "${ascii(String(body.title))}")`,
    `// Coverage: ${start} to ${end} (Israel calendar dates).`,
    '// Rules: Tishrei run (Erev Rosh Hashana..Shmini Atzeret), Pesach run (Erev Pesach..Pesach VII),',
    "// other yom tov days and their eve, Yom HaZikaron + Yom HaAtzma'ut. See the script header.",
    '',
    `export const IL_CALENDAR_SOURCE = ${JSON.stringify({ url: SOURCE_URL, fetchedAt, provider: 'hebcal.com' })} as const;`,
    '',
    `export const IL_CALENDAR_COVERAGE = ${JSON.stringify({ from: start, to: end })} as const;`,
    '',
    'export const IL_BLACKOUT_DATES: ReadonlyArray<{ date: string; reason: string }> = [',
    ...dates.map((d) => `  { date: '${d.date}', reason: ${JSON.stringify(ascii(d.reason))} },`),
    '];',
    '',
  ];
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${dates.length} blackout dates (${start}..${end})`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((err) => { console.error(err); process.exit(1); });
}
