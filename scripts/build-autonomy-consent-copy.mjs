import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'docs', 'copy', 'autonomous-ads-consent-bundle.json');
const outputPath = path.join(root, 'src', 'lib', 'google-ads', 'autonomyCopy.ts');
const requiredKeys = [
  'AUTONOMY_CONSENT_LABEL',
  'AUTONOMY_SCOPE_SUMMARY',
  'AUTONOMY_LIMITS_SUMMARY',
  'AUTONOMY_STOP_SUMMARY',
  'AUTONOMY_AUDIT_SUMMARY',
  'AUTONOMY_SHADOW_NOTICE',
];

const source = readFileSync(sourcePath, 'utf8');
const bundle = JSON.parse(source);
if (!bundle || typeof bundle !== 'object' || Array.isArray(bundle)) {
  throw new Error('Autonomy consent bundle must be a JSON object.');
}
const actualKeys = Object.keys(bundle).sort();
const expectedKeys = [...requiredKeys].sort();
if (actualKeys.length !== expectedKeys.length || actualKeys.some((key, index) => key !== expectedKeys[index])) {
  throw new Error(`Autonomy consent bundle keys must exactly match: ${expectedKeys.join(', ')}`);
}
for (const key of requiredKeys) {
  if (typeof bundle[key] !== 'string' || !bundle[key].trim()) {
    throw new Error(`Autonomy consent bundle value for ${key} must be a non-empty string.`);
  }
}

const termsVersion = `bundle-sha256:${createHash('sha256').update(source, 'utf8').digest('hex')}`;
const generated = [
  '// Generated by scripts/build-autonomy-consent-copy.mjs. Do not edit manually.',
  `export const AUTONOMY_TERMS_VERSION = ${JSON.stringify(termsVersion)} as const;`,
  `export const autonomyConsentCopy = ${JSON.stringify(bundle, null, 2)} as const;`,
  '',
].join('\n');
writeFileSync(outputPath, generated, 'utf8');
