#!/usr/bin/env node
// Generates src/lib/site-bot/research/priceLexiconData.ts from the Noa-gated price lexicon
// (docs/copy/site-bot-price-lexicon-2026-11-10.json), byte-exact. The generated module escapes every non-ASCII
// character as \uXXXX, so it holds ZERO Hebrew bytes and survives the standalone build (docs/ is not traced).
// Re-run after any lexicon change: node scripts/site-bot/build-price-lexicon.mjs
// researchDepth.test.ts fails while the generated module and the JSON differ.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE = 'docs/copy/site-bot-price-lexicon-2026-11-10.json';
const TARGET = 'src/lib/site-bot/research/priceLexiconData.ts';

const raw = JSON.parse(fs.readFileSync(path.join(ROOT, SOURCE), 'utf8'));
for (const key of ['priceStems', 'pricePhrases']) {
  if (!Array.isArray(raw[key]) || !raw[key].every(item => typeof item === 'string')) throw new Error(`${SOURCE}: ${key} must be a string array`);
}
const ascii = value => JSON.stringify(value).replace(/[\u007F-￿]/g, ch => `\\u${ch.charCodeAt(0).toString(16).toUpperCase().padStart(4, '0')}`);
const body = `/**
 * GENERATED by scripts/site-bot/build-price-lexicon.mjs from ${SOURCE} (Tamar -> Noa, byte-exact). Do not edit.
 * HEBREW-SAFETY: every non-ASCII character is a \\uXXXX escape (zero Hebrew bytes).
 */
import type { PriceLexicon } from './depthFilters';

export const PRICE_LEXICON_SOURCE = ${JSON.stringify(SOURCE)};

export const PRICE_LEXICON_DATA: PriceLexicon = {
  priceStems: ${ascii(raw.priceStems)},
  pricePhrases: ${ascii(raw.pricePhrases)},
};
`;
fs.writeFileSync(path.join(ROOT, TARGET), body);
console.log(`wrote ${TARGET}: ${raw.priceStems.length} stems, ${raw.pricePhrases.length} phrases`);
