// Builds the /site-bot and /google-ads landing-page copy modules from the approved round-2 sources in docs/copy.
// HEBREW-SAFETY: this script is ASCII-only and never contains Hebrew. Every value is read, byte-exact, from the
// source file (`key :: value`, one field per line) and serialized with JSON.stringify.
//
// Prices are never typed into the copy: each page's monthly price (Site Bot 199, Ads Bot 249) is replaced by the
// `{net}` token here, with an asserted count, and filled back at runtime from src/lib/payments/plans.ts
// (fillLandingCopy). landingCopy.test.ts proves that the filled copy equals the source file field for field.
//
// To change the copy: change the docs/copy source (Tamar -> Noa), then run `node scripts/build-landing-copy.mjs`.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

export const NET_TOKEN = '{net}';

export const PAGES = [
  {
    id: 'site-bot',
    exportName: 'SITE_BOT_LANDING_COPY_SOURCE',
    source: new URL('../docs/copy/site-bot-r2-final-candidate-2026-11-12.txt', import.meta.url),
    output: new URL('../src/lib/site-bot/landingCopy.generated.ts', import.meta.url),
    price: '199',
    // hero.badge, price.body, faq[1].a, seo.description
    priceCount: 4,
  },
  {
    id: 'google-ads',
    exportName: 'GOOGLE_ADS_LANDING_COPY_SOURCE',
    source: new URL('../docs/copy/google-ads-r2-final-candidate-2026-11-12.txt', import.meta.url),
    output: new URL('../src/lib/google-ads/landingCopy.generated.ts', import.meta.url),
    price: '249',
    // hero.subhead, offer.h2, offer.body, faq[0].q, faq[0].a, faq[3].a, faq[8].a, seo.title, seo.description,
    // seo.jsonld.webpage_description, seo.jsonld.service_description
    priceCount: 11,
  },
];

/** "key :: value" lines -> [[key, value], ...] in file order. Fails closed on anything else. */
export function parseFields(text) {
  if (text.includes('\r')) throw new Error('CRLF in source');
  const out = [];
  const seen = new Set();
  for (const line of text.split('\n')) {
    if (line === '') continue;
    const at = line.indexOf(' :: ');
    if (at <= 0) throw new Error(`Not a "key :: value" line: ${line.slice(0, 40)}`);
    const key = line.slice(0, at);
    const value = line.slice(at + 4);
    if (!/^[a-z_][a-z0-9_]*(\.[a-z_][a-z0-9_]*|\[\d+\])*$/.test(key)) throw new Error(`Bad key: ${key}`);
    if (seen.has(key)) throw new Error(`Duplicate key: ${key}`);
    if (!value || value !== value.trim()) throw new Error(`Empty or padded value: ${key}`);
    seen.add(key);
    out.push([key, value]);
  }
  return out;
}

/** "faq[2].q" -> ['faq', 2, 'q'] */
export function keyPath(key) {
  return [...key.matchAll(/([a-z_][a-z0-9_]*)|\[(\d+)\]/g)].map(m => (m[1] !== undefined ? m[1] : Number(m[2])));
}

/** Flat fields -> a nested object; numeric segments become dense arrays. */
export function nest(fields) {
  const root = {};
  for (const [key, value] of fields) {
    const parts = keyPath(key);
    let node = root;
    parts.forEach((part, i) => {
      const last = i === parts.length - 1;
      if (last) {
        if (part in node) throw new Error(`Key collides with a group: ${key}`);
        node[part] = value;
        return;
      }
      if (!(part in node)) node[part] = typeof parts[i + 1] === 'number' ? [] : {};
      node = node[part];
      if (typeof node !== 'object') throw new Error(`Key nests under a value: ${key}`);
    });
  }
  const check = (v, at) => {
    if (Array.isArray(v)) { for (let i = 0; i < v.length; i++) { if (v[i] === undefined) throw new Error(`Gap at ${at}[${i}]`); check(v[i], `${at}[${i}]`); } }
    else if (v && typeof v === 'object') Object.entries(v).forEach(([k, item]) => check(item, `${at}.${k}`));
  };
  check(root, '');
  return root;
}

/** The price as a standalone number (not part of 1990, 2,199, 19.9 ...). */
export function priceRegex(price) {
  return new RegExp(`(?<![\\d.,])${price}(?![\\d.,])`, 'g');
}

export function tokenize(fields, price, expectedCount) {
  let count = 0;
  const out = fields.map(([key, value]) => {
    if (value.includes('{') || value.includes('}')) throw new Error(`Brace in source value: ${key}`);
    return [key, value.replace(priceRegex(price), () => { count++; return NET_TOKEN; })];
  });
  if (count !== expectedCount) throw new Error(`Expected ${expectedCount} price tokens for ${price}, found ${count}`);
  return out;
}

export function generate(page, sourceText) {
  const tokenized = nest(tokenize(parseFields(sourceText), page.price, page.priceCount));
  const rel = fileURLToPath(page.source).split('/docs/copy/')[1];
  return [
    '// GENERATED by scripts/build-landing-copy.mjs -- do not edit by hand.',
    `// Source (byte-exact, approved r2 copy): docs/copy/${rel}`,
    `// The page price is the ${NET_TOKEN} token, filled from src/lib/payments/plans.ts by fillLandingCopy().`,
    `export const ${page.exportName} = ${JSON.stringify(tokenized, null, 2)} as const;`,
    '',
  ].join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const page of PAGES) {
    const next = generate(page, fs.readFileSync(page.source, 'utf8'));
    const current = fs.existsSync(page.output) ? fs.readFileSync(page.output, 'utf8') : null;
    if (check) {
      if (current !== next) { stale++; console.error(`stale: ${fileURLToPath(page.output)}`); }
    } else if (current !== next) {
      fs.writeFileSync(page.output, next);
      console.log(`wrote ${fileURLToPath(page.output)}`);
    } else {
      console.log(`unchanged ${fileURLToPath(page.output)}`);
    }
  }
  if (stale) process.exit(1);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
