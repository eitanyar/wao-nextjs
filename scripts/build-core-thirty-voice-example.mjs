// Builds src/lib/lp/coreThirtyVoiceExample.generated.ts: the core-30 write prompt's voice example (Fable 5.2 D3b).
// HEBREW-SAFETY: this script is ASCII-only and never contains Hebrew. The example is the `copy` object at index 2 of the
// blind-test Qwen output (electrician, Tel Aviv, svc0-city0), read byte-exact and serialized with JSON.stringify.
// Usage: node scripts/build-core-thirty-voice-example.mjs
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SOURCE = fileURLToPath(new URL('../docs/research/site-bot/blindtest-2026-11-15/qwen.json', import.meta.url));
export const OUTPUT = fileURLToPath(new URL('../src/lib/lp/coreThirtyVoiceExample.generated.ts', import.meta.url));

export function readVoiceExample(file = SOURCE) {
  const rows = JSON.parse(fs.readFileSync(file, 'utf8'));
  const row = rows[2];
  if (!row || row.trade !== 'electrician' || row.node !== 'svc0-city0' || !row.copy || typeof row.copy !== 'object') {
    throw new Error('qwen.json[2] is not the electrician svc0-city0 page');
  }
  return row.copy;
}

export function renderModule(copy) {
  return [
    '// GENERATED by scripts/build-core-thirty-voice-example.mjs from',
    '// docs/research/site-bot/blindtest-2026-11-15/qwen.json (index 2, field `copy`). Do not edit by hand.',
    '// Voice example for the core-30 write prompt (Fable 5.2 D3b): register and rhythm only, never facts.',
    '',
    `export const CORE_THIRTY_VOICE_EXAMPLE_JSON: string = ${JSON.stringify(JSON.stringify(copy))};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  fs.writeFileSync(OUTPUT, renderModule(readVoiceExample()));
  console.log('wrote src/lib/lp/coreThirtyVoiceExample.generated.ts');
}
