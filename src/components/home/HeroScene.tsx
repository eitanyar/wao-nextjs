// Homepage hero visual (docs/missions/homepage-hero-motion-2026-11-15.md). An AI-made photo of a laptop on a
// plumber's workbench, with a live "browser window" laid onto its screen: the product's own Google ad preview above
// the landing page it points to, and a chat chip standing for the intake chat. Server-rendered; the only client JS is
// HeroMotionButton (the motion controller).
//
// a11y: the whole scene is aria-hidden + inert. It illustrates the hero's promise, and the hero CTA next to it
// carries the action; a screen reader would otherwise read a second business's page (its own h1, nav, phone)
// inside WAO's homepage. The sr-only description outside the scene says what it shows.
//
// Geometry: the stage is the photo's own pixel grid (HERO_SCENE.width x height), scaled to the box with
// scale: tan(atan2(100cqw, var(--scene-w))) (a unitless ratio of two lengths, no JS). The window is a 960x605 virtual
// screen mapped onto the fitted screen corners by one matrix3d. Browsers without trig / container units skip the
// stage and show the photo with its screen switched off (the build step paints it near-black).
//
// Motion (docs/specs/hero-motion-spec-maya-2026-11-15.md): one layer per showcase entry (src/lib/home/heroShowcases.ts);
// the chat, results page, highlight and pointer layers are SSR'd at opacity 0 and run as CSS keyframes
// (./heroMotion.module.css, generated by scripts/build-hero-motion-css.mjs) inside the [data-active] entry while the
// wrapper says data-motion="playing"; HeroMotionButton flips it. The SSR frame is entry 1's resting frame (CLS 0).
// Strings: src/content/hero-motion-strings-2026-11-15.json and src/content/hero-showcases.json (applied by script).
import type { CSSProperties } from "react";
import GoogleAdPreview from "@/components/google-ads/GoogleAdPreview";
import motion from "@/content/hero-motion-strings-2026-11-15.json";
import HeroMotionButton from "./HeroMotionButton";
import m from "./heroMotion.module.css";
import { HERO_SCENE } from "@/data/heroScene";
import { HERO_STAGE_FIT_INLINE } from "@/lib/home/heroStageFit";
import {
  HERO_WINDOW_LP_HEIGHT,
  HERO_WINDOW_SERP,
  HERO_WINDOW_SIZE,
  HERO_WINDOW_TAB_BAR,
  heroWindowData,
  heroWindowTransform,
} from "@/lib/home/heroWindow";
import { SHOWCASES, SHOWCASE_LOOP, showcaseQuery, showcaseSteps, type ShowcaseEntry } from "@/lib/home/heroShowcases";

const pct = (v: number) => `${+((v / HERO_SCENE.height) * 100).toFixed(4)}%`;

/** Rendered width of the scene, for the image srcset: half the 1112px container above 1024px, else the container. */
const SCENE_SIZES = "(min-width: 1024px) 560px, (max-width: 480px) calc(100vw - 96px), calc(100vw - 48px)";

const STEP_CLASS = [m.s1, m.s2, m.s3];
const px = (v: number) => `${v}px`;

/** The intake chat as it plays: one question at a time, three ready-made chips, then the ready cue. */
function MotionChat({ entry }: { entry: ShowcaseEntry }) {
  return (
    <div className={m.chat}>
      {showcaseSteps(entry).map((step, i) => (
        <div key={i} className={`${m.step} ${STEP_CLASS[i]}`}>
          <div className={m.q}>
            <p className={m.bubble}>{step.question}</p>
            <span className={m.avatar} />
          </div>
          <div className={m.chips}>
            {step.chips.map((chip, j) =>
              j === step.answer ? (
                <span key={j} className={`${m.chip} ${m.pick}`} data-label={chip}>{chip}</span>
              ) : (
                <span key={j} className={`${m.chip} ${m.dim}`}>{chip}</span>
              ),
            )}
          </div>
        </div>
      ))}
      <div className={m.ready}>
        <svg viewBox="0 0 24 24" aria-hidden="true">
          <circle cx="12" cy="12" r="12" fill="#36ddb5" />
          <path d="M6.5 12.5l3.5 3.5 7.5-8" fill="none" stroke="#101416" strokeWidth="2.4" strokeLinecap="round" strokeLinejoin="round" />
        </svg>
        <span>{motion.ready}</span>
      </div>
    </div>
  );
}

/**
 * The Google results page the chat collapses into (Eitan 2026-11-15): a plain search box holding the query (the
 * entry's service + area answers, concatenated; no new copy), its ad as the first, sponsored result at a readable
 * size, and the results area fading to white. No organic results, no logo.
 */
function MotionResults({ entry, ad }: { entry: ShowcaseEntry; ad: ReturnType<typeof heroWindowData>["ad"] }) {
  return (
    <div className={m.serp}>
      <div className={m.search}>
        <svg viewBox="0 0 24 24" aria-hidden="true">
          <circle cx="10.5" cy="10.5" r="6.5" />
          <path d="M15.5 15.5L21 21" />
        </svg>
        <span>{showcaseQuery(entry)}</span>
      </div>
      <div className={m.serpAd}>
        <div className={m.serpScale}>
          <GoogleAdPreview displayUrl={ad.displayUrl} headlines={ad.headlines} descriptions={ad.descriptions} />
          {entry.geometry.resultsAdLines.map(([top, width], i) => (
            <span key={i} className={m.hlAd} style={{ top: px(top), width: px(width) }} />
          ))}
          <div className={m.fade} />
        </div>
      </div>
    </div>
  );
}

/** A standard arrow cursor, tip at (0,0). The outer layer moves X, the inner Y (two curves, so each hop arcs). */
function MotionPointer() {
  return (
    <span className={m.ptr} data-hm-pointer="">
      <span className={m.ptrY}>
        <span className={m.click} />
        <span className={m.press}>
          <svg viewBox="0 0 24 36" aria-hidden="true">
            <path d="M0 0v27.5l6.6-6.2 4.6 10.6 4.7-2-4.6-10.4h9.1z" fill="#fff" stroke="#000" strokeWidth="2" strokeLinejoin="round" />
          </svg>
        </span>
      </span>
    </span>
  );
}

/** One showcase business: its resting window (tab, ad strip, LP) plus its motion layers. */
function ShowcaseLayer({ entry, index }: { entry: ShowcaseEntry; index: number }) {
  const w = heroWindowData(entry);
  const g = entry.geometry;
  const [bl, bt, bw, bh, br, bc] = g.callButton;
  const ring: CSSProperties = { left: px(bl), top: px(bt), width: px(bw), height: px(bh), borderRadius: px(br), borderColor: bc };
  // Only the first entry's iframe loads with the page; the controller sets the next one's src during a loop rest.
  const src = index === 0 ? { src: w.lpPath } : { "data-src": w.lpPath };
  return (
    <div className={`${m.entry} ${m[`e${index}`] ?? ""}`} data-hm-entry="" data-active={index === 0 ? "" : undefined}>
      <div className="hero-window-tabs" style={{ height: HERO_WINDOW_TAB_BAR }}>
        <span className="hero-window-tab">
          <span className="hero-window-favicon" />
          <span className="hero-window-tab-title">{w.tabTitle}</span>
        </span>
      </div>
      <div className={`hero-window-serp ${m.ad}`} style={{ height: HERO_WINDOW_SERP }}>
        <GoogleAdPreview displayUrl={w.ad.displayUrl} headlines={w.ad.headlines} descriptions={w.ad.descriptions} />
      </div>
      <div className={`hero-window-lpwrap ${m.lp}`} style={{ height: HERO_WINDOW_LP_HEIGHT }}>
        <iframe
          className="hero-window-lp"
          {...src}
          title={w.tabTitle}
          width={HERO_WINDOW_SIZE.width}
          height={HERO_WINDOW_LP_HEIGHT}
          loading="lazy"
          tabIndex={-1}
        />
        {g.lpHeadlineLines.map(([left, top, width, height], i) => (
          <span key={i} className={m.hlLp} style={{ left: px(left), top: px(top), width: px(width), height: px(height) }} />
        ))}
        <span className={m.ring} style={ring} />
      </div>
      <MotionResults entry={entry} ad={w.ad} />
      <MotionChat entry={entry} />
      <span className={`hero-window-chat ${m.corner}`}>
        <svg viewBox="0 0 24 24" aria-hidden="true">
          <path d="M21 11.5a8.4 8.4 0 0 1-.9 3.8 8.5 8.5 0 0 1-7.6 4.7 8.4 8.4 0 0 1-3.8-.9L3 21l1.9-5.7a8.4 8.4 0 0 1-.9-3.8 8.5 8.5 0 0 1 4.7-7.6 8.4 8.4 0 0 1 3.8-.9h.5a8.5 8.5 0 0 1 8 8v.5z" />
        </svg>
      </span>
      <MotionPointer />
    </div>
  );
}

/** pause_label / play_label are NEEDED from waocopy; until both exist the loop stays dormant (validated at build). */
const loopLabels = motion as { pause_label?: string; play_label?: string };

export default function HeroScene() {
  return (
    <div className={`hero-scene-wrap ${m.wrap}`} data-motion="rest" data-loop={SHOWCASE_LOOP ? "" : undefined}>
      <div
        className="hero-scene"
        data-hm-scene=""
        aria-hidden="true"
        inert
        style={{ aspectRatio: `${HERO_SCENE.width} / ${HERO_SCENE.height}`, ["--scene-w" as string]: `${HERO_SCENE.width}px` }}
        suppressHydrationWarning
      >
        {HERO_SCENE.tiles.map((tile) => (
          <picture key={tile.id} className="hero-scene-tile" style={{ top: pct(tile.top), height: pct(tile.height) }}>
            <source type="image/avif" srcSet={tile.avif} sizes={SCENE_SIZES} />
            <img
              src={tile.fallback}
              srcSet={tile.webp}
              sizes={SCENE_SIZES}
              width={tile.fallbackWidth}
              height={tile.fallbackHeight}
              alt=""
              decoding="async"
              fetchPriority="low"
              loading="lazy"
            />
          </picture>
        ))}
        <div className="hero-stage" style={{ width: HERO_SCENE.width, height: HERO_SCENE.height }} suppressHydrationWarning>
          <div
            className="hero-window"
            style={{ width: HERO_WINDOW_SIZE.width, height: HERO_WINDOW_SIZE.height, transform: heroWindowTransform() }}
          >
            {SHOWCASES.map((entry, i) => (
              <ShowcaseLayer key={entry.id} entry={entry} index={i} />
            ))}
          </div>
        </div>
        {/* Sets the stage scale before first paint (WebKit miscomputes the CSS fit); heroStageFit.ts keeps it fitted. */}
        <script dangerouslySetInnerHTML={{ __html: HERO_STAGE_FIT_INLINE }} />
      </div>
      <HeroMotionButton
        labels={{
          skip: motion.skip_label,
          replay: motion.replay_label,
          ...(SHOWCASE_LOOP ? { pause: loopLabels.pause_label, play: loopLabels.play_label } : {}),
        }}
        classes={[m.btn, m.icoSkip, m.icoReplay, m.icoPause, m.icoPlay]}
      />
      <p className="sr-only">{motion.sr_description}</p>
      <p className={m.cue} aria-hidden="true">{motion.static_cue}</p>
    </div>
  );
}
